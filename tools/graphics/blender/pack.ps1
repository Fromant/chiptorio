# Pack render outputs without changing their pixels; optionally install all four directions.
param([string]$OutputDirectory=(Join-Path $PSScriptRoot 'renders/final'),[switch]$Install,[switch]$KeepFrames)
$ErrorActionPreference='Stop'
Add-Type -AssemblyName System.Drawing
$out=[IO.Path]::GetFullPath($OutputDirectory)
$m=Get-Content -LiteralPath (Join-Path $out 'render-manifest.json') -Raw|ConvertFrom-Json
if($Install){foreach($d in @('north','east','south','west')){if(-not $m.directions.$d){throw 'Install requires all four cardinal directions.'}}}
$lua=New-Object System.Collections.Generic.List[string]
$lua.Add('-- Generated by pack.ps1. Regenerate; do not hand-edit.')
$lua.Add('return {')
$cleanup=New-Object System.Collections.Generic.List[string]
foreach($prop in $m.directions.PSObject.Properties){
 $d=$prop.Name;$spec=$prop.Value;$size=[int]$spec.size;$cols=[int]$m.line_length;$rows=[int][Math]::Ceiling($m.frames/$cols)
 $sheet=New-Object Drawing.Bitmap ($cols*$size),($rows*$size)
 $g=[Drawing.Graphics]::FromImage($sheet);$g.CompositingMode=[Drawing.Drawing2D.CompositingMode]::SourceCopy
 $lx=$size;$hx=0;$ly=$size;$hy=0
 $firstBytes=$null;$different=$false
 for($f=0;$f -lt $m.frames;$f++){
  $path=[IO.Path]::GetFullPath((Join-Path $out $spec.files[$f]))
  if(-not $path.StartsWith($out+[IO.Path]::DirectorySeparatorChar,[StringComparison]::OrdinalIgnoreCase)){throw 'Frame path escapes output directory'}
  $img=[Drawing.Bitmap]::FromFile($path)
  try {
   if($img.Width -ne $size -or $img.Height -ne $size){throw "Wrong frame dimensions: $path"}
   # Blender PNGs carry 72-DPI metadata. Explicit pixel rectangles prevent
   # GDI+ from silently enlarging them to the destination bitmap's 96 DPI.
   $rect=New-Object Drawing.Rectangle (($f%$cols)*$size),(([int][Math]::Floor($f/$cols))*$size),$size,$size
   $g.DrawImage($img,$rect,0,0,$size,$size,[Drawing.GraphicsUnit]::Pixel)
   $g.Flush()
   # Verify opaque source pixels survive packing at exactly the same offsets.
   for($py=0;$py -lt $size;$py+=12){for($px=0;$px -lt $size;$px+=12){
    $sourcePixel=$img.GetPixel($px,$py)
    if($sourcePixel.A -eq 255 -and $sheet.GetPixel($rect.X+$px,$rect.Y+$py).ToArgb() -ne $sourcePixel.ToArgb()){
      throw "Sprite packing changed pixel placement: $d frame $f"
    }
   }}
   # Full alpha bounds of every frame protect the placement area, not just frame zero.
   for($y=0;$y -lt $size;$y++){for($x=0;$x -lt $size;$x++){if($img.GetPixel($x,$y).A -gt 8){$lx=[Math]::Min($lx,$x);$hx=[Math]::Max($hx,$x);$ly=[Math]::Min($ly,$y);$hy=[Math]::Max($hy,$y)}}}
  } finally {$img.Dispose()}
  if($f -eq 0){$firstBytes=[Convert]::ToBase64String([IO.File]::ReadAllBytes($path))}elseif([Convert]::ToBase64String([IO.File]::ReadAllBytes($path)) -ne $firstBytes){$different=$true}
  if($f -gt 0){$cleanup.Add($path)}
 }
 if($m.frames -gt 1 -and -not $different){throw "Animation is frozen: $d"}
 $g.Dispose()
 $sheetName="server-rack_${d}_sheet.png"
 $sheet.Save((Join-Path $out $sheetName),[Drawing.Imaging.ImageFormat]::Png);$sheet.Dispose()
 $scale=if($spec.sprite_scale){[double]$spec.sprite_scale}else{[double]$m.sprite_scale}
 $sx=(($size/2)-($lx+$hx)/2)*$scale/32;$sy=(($size/2)-($ly+$hy)/2)*$scale/32
 if($d -ne 'hero' -and (($hx-$lx)*$scale -gt 96 -or ($hy-$ly)*$scale -gt 96)){throw "Animated silhouette exceeds 3x3: $d"}
 $xText=$sx.ToString('R',[Globalization.CultureInfo]::InvariantCulture);$yText=$sy.ToString('R',[Globalization.CultureInfo]::InvariantCulture)
 $scaleText=$scale.ToString('R',[Globalization.CultureInfo]::InvariantCulture)
 $shadow=($m.shadows -ne $false) -and (Test-Path -LiteralPath (Join-Path $out "server-rack_${d}_shadow.png"))
 if($shadow -and $d -ne 'hero' -and $m.shadow_direction -eq 'screen-right'){
  $body=[Drawing.Bitmap]::FromFile((Join-Path $out $spec.files[0]))
  $shade=[Drawing.Bitmap]::FromFile((Join-Path $out "server-rack_${d}_shadow.png"))
  $mass=0.0;$moment=0.0
  try{
   for($py=0;$py -lt $size;$py++){for($px=0;$px -lt $size;$px++){
    $alpha=$shade.GetPixel($px,$py).A
    if($alpha -gt 12 -and $body.GetPixel($px,$py).A -lt 8){$mass+=$alpha;$moment+=$alpha*$px}
   }}
  }finally{$body.Dispose();$shade.Dispose()}
  if($mass -eq 0 -or $moment/$mass -lt $size*.55){throw "Shadow direction regression: $d must cast screen-right"}
 }
 $lua.Add("  $d = { layers = {")
 $lua.Add("    { filename='__chiptorio__/graphics/entity/server-rack/$sheetName', width=$size, height=$size, frame_count=$($m.frames), line_length=$cols, animation_speed=0.5, scale=$scaleText, shift={$xText,$yText} },")
 if($shadow){$lua.Add("    { filename='__chiptorio__/graphics/entity/server-rack/server-rack_${d}_shadow.png', width=$size, height=$size, repeat_count=$($m.frames), scale=$scaleText, shift={$xText,$yText}, draw_as_shadow=true },")}
 $lua.Add('  } },')
 Write-Host "$d : $($m.frames) frames, ${size}px, bounds $lx,$ly to $hx,$hy; device=$($m.device)"
}
$lua.Add('}')
$lua | Set-Content -LiteralPath (Join-Path $out 'sprite-def.lua') -Encoding UTF8
if($Install){
 $dest=Join-Path (Split-Path (Split-Path (Split-Path $PSScriptRoot -Parent) -Parent) -Parent) 'graphics/entity/server-rack'
 New-Item -ItemType Directory -Force $dest|Out-Null
 foreach($d in @('north','east','south','west')){
  Copy-Item -LiteralPath (Join-Path $out "server-rack_${d}_sheet.png") -Destination $dest
  if($m.shadows -ne $false -and (Test-Path -LiteralPath (Join-Path $out "server-rack_${d}_shadow.png"))){Copy-Item -LiteralPath (Join-Path $out "server-rack_${d}_shadow.png") -Destination $dest}
 }
 Copy-Item -LiteralPath (Join-Path $out 'sprite-def.lua') -Destination $dest
}
if(-not $KeepFrames){foreach($path in $cleanup){Remove-Item -LiteralPath $path}}
# Self-contained viewer plays exported sheets, so reviewers inspect exactly what ships.
$names=ConvertTo-Json -InputObject @($m.directions.PSObject.Properties.Name) -Compress
$previewSize=@($m.directions.PSObject.Properties)[0].Value.size
@"
<!doctype html><meta charset="utf-8"><title>Chiptorio animated rack</title>
<style>body{background:#30342f;color:#e4e0d1;font:16px system-ui;margin:32px}main{display:flex;flex-wrap:wrap}canvas{background:repeating-conic-gradient(#373c35 0% 25%,#343931 0% 50%) 0/32px 32px;margin:8px}button{padding:8px 18px}</style>
<h1>3 x 3 server enclosure</h1><p>Exported sprite sheets - fans rotate and activity lamps blink.</p><button id="pause">Pause</button><main></main>
<script>
const names=$names,frames=$($m.frames),cols=$($m.line_length),size=$previewSize;
let running=true,frame=0; document.querySelector('button').onclick=()=>{running=!running;document.querySelector('button').textContent=running?'Pause':'Play'};
for(const name of names){const box=document.createElement('section');box.innerHTML='<h2>'+name+'</h2>';const c=document.createElement('canvas');c.width=c.height=size;box.append(c);document.querySelector('main').append(box);const image=new Image();image.src='server-rack_'+name+'_sheet.png';const ctx=c.getContext('2d');setInterval(()=>{ctx.clearRect(0,0,size,size);if(image.complete)ctx.drawImage(image,(frame%cols)*size,Math.floor(frame/cols)*size,size,size,0,0,size,size)},1000/30)}
setInterval(()=>{if(running)frame=(frame+1)%frames},1000/30);
</script>
"@ | Set-Content -LiteralPath (Join-Path $out 'preview.html') -Encoding UTF8
